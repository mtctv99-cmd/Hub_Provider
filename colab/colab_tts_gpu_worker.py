def make_wav(samples, sample_rate):
    """Convert mono samples to 16-bit PCM WAV."""
    import numpy as np
    import wave

    data = np.asarray(samples).reshape(-1)
    if data.dtype.kind == 'f':
        data = (np.clip(data, -1.0, 1.0) * 32767.0).astype('<i2')
    else:
        data = np.clip(data, -32768, 32767).astype('<i2')
    buf = io.BytesIO()
    with wave.open(buf, 'wb') as wav:
        wav.setnchannels(1)
        wav.setsampwidth(2)
        wav.setframerate(sample_rate)
        wav.writeframes(data.tobytes())
    return buf.getvalue()


class PiperVoice:
    """Cached piper-tts voice session."""
    def __init__(self, model_path, use_cuda=True):
        import wave
        self.wave = wave
        from piper.voice import PiperVoice as Backend
        try:
            self.voice = Backend.load(str(model_path), use_cuda=use_cuda)
            LOG.info("Loaded Piper voice %s (CUDA=%s)", model_path.name, use_cuda)
        except Exception as exc:
            if use_cuda:
                LOG.warning("CUDA load failed for %s, falling back to CPU: %s", model_path.name, exc)
                self.voice = Backend.load(str(model_path), use_cuda=False)
            else:
                raise

    def synthesize(self, text):
        buf = io.BytesIO()
        with self.wave.open(buf, 'wb') as wav:
            if hasattr(self.voice, 'synthesize_wav'):
                self.voice.synthesize_wav(text, wav)
            else:
                self.voice.synthesize(text, wav)
        return buf.getvalue()


class KhmerVoice:
    """Cached ONNX session with Khmer character vocabulary."""
    def __init__(self, session, config, sample_rate=22050):
        self.session = session
        self.vocab = {c: i for i, c in enumerate(config['vocab'])}
        self.blank_id = self.vocab.get(config.get('blank', ''))
        self.add_blank = bool(config.get('add_blank'))
        self.sample_rate = sample_rate

    @classmethod
    def load(cls, model_path, config_path, sample_rate=22050, providers=None):
        import onnxruntime as ort
        if providers is None:
            providers = ['CUDAExecutionProvider', 'CPUExecutionProvider']
        with open(config_path, 'r', encoding='utf-8') as f:
            config = json.load(f)
        try:
            session = ort.InferenceSession(str(model_path), providers=providers)
            actual_prov = session.get_providers()
            LOG.info("Loaded Khmer ONNX %s with providers: %s", Path(model_path).name, actual_prov)
        except Exception as exc:
            LOG.warning("Failed with preferred providers %s: %s; falling back to CPU", providers, exc)
            session = ort.InferenceSession(str(model_path), providers=['CPUExecutionProvider'])
        return cls(session, config, sample_rate)

    def synthesize(self, text):
        import numpy as np
        ids = [self.vocab[c] for c in text if c in self.vocab]
        if not ids:
            raise ValueError('Khmer text contains no supported vocabulary characters')
        if self.add_blank and self.blank_id is not None:
            interleaved = [self.blank_id]
            for tok in ids:
                interleaved.extend((tok, self.blank_id))
            ids = interleaved
        x = np.asarray([ids], dtype=np.int64)
        x_lengths = np.asarray([len(ids)], dtype=np.int64)
        audio = np.asarray(self.session.run(None, {'x': x, 'x_lengths': x_lengths})[0]).reshape(-1)
        if len(audio) == 0:
            raise ValueError('Empty audio generated by Khmer model')
        return make_wav(audio, self.sample_rate)


class VoiceLane:
    """Manages concurrent worker threads for one voice."""
    def __init__(self, name, voice, queue_size=32, num_threads=4):
        self.name = name
        self.voice = voice
        self.jobs = queue.Queue(maxsize=queue_size)
        self.threads = [
            threading.Thread(target=self._run, name=f"lane-{name}-{i}", daemon=True)
            for i in range(num_threads)
        ]
        for t in self.threads:
            t.start()

    def _run(self):
        while True:
            item = self.jobs.get()
            if item is None:
                break
            msg, send = item
            rid = msg.get('request_id')
            try:
                t0 = time.monotonic()
                audio = self.voice.synthesize(msg['text'])
                dt = (time.monotonic() - t0) * 1000.0
                send({
                    'type': 'audio_result',
                    'request_id': rid,
                    'mime': 'audio/wav',
                    'audio_base64': base64.b64encode(audio).decode('ascii'),
                    'done': True
                })
                LOG.info('[TTS] Voice %s completed %s in %.1fms (%d bytes)', self.name, rid, dt, len(audio))
            except Exception as exc:
                LOG.error('[TTS] Voice %s failed %s: %s', self.name, rid, exc)
                send({'type': 'error', 'request_id': rid, 'error': str(exc)})
            finally:
                self.jobs.task_done()

    def close(self):
        for _ in self.threads:
            self.jobs.put(None)
        for t in self.threads:
            t.join(timeout=2.0)


class ColabTTSWorker:
    def __init__(self, voices, queue_size=32, threads_per_voice=4):
        self.voices = {
            name: VoiceLane(name, voice, queue_size, num_threads=threads_per_voice)
            for name, voice in voices.items()
        }

    def dispatch(self, msg, send):
        typ, rid, model = msg.get('type'), msg.get('request_id'), msg.get('model')
        if typ == 'ping':
            send({'type': 'pong'})
            return
        if typ != 'tts_request' or not isinstance(rid, str) or not rid:
            return
        voice_id = msg.get('voice_id') or (model.removeprefix('piper:') if isinstance(model, str) else '')
        lane = self.voices.get(voice_id)
        if not lane or (isinstance(model, str) and model != 'piper:' + voice_id):
            send({'type': 'error', 'request_id': rid, 'error': f'Unsupported voice: {voice_id}'})
            return
        text = msg.get('text')
        if not isinstance(text, str) or not text.strip():
            send({'type': 'error', 'request_id': rid, 'error': 'Empty text'})
            return
        try:
            lane.jobs.put_nowait((msg, send))
        except queue.Full:
            LOG.error('[DISPATCH] Queue full for %s on %s', voice_id, rid)
            send({'type': 'error', 'request_id': rid, 'error': 'Voice queue full'})

    def close(self):
        for lane in self.voices.values():
            lane.close()


def ensure_models(models_dir: Path, base_url: str):
    """Automatically ensure all 3 ONNX models and configs are downloaded."""
    models_dir = Path(models_dir)
    models_dir.mkdir(parents=True, exist_ok=True)
    base_url = base_url.rstrip('/')

    # Check for pre-existing files
    nh_onnx = models_dir / 'ngoc_huyen' / 'ngochuyennew.onnx' if (models_dir / 'ngoc_huyen' / 'ngochuyennew.onnx').is_file() else models_dir / 'ngochuyennew.onnx'
    nh_json = models_dir / 'ngoc_huyen' / 'ngochuyennew.onnx.json' if (models_dir / 'ngoc_huyen' / 'ngochuyennew.onnx.json').is_file() else models_dir / 'ngochuyennew.onnx.json'

    specs = {
        'ngochuyennew': {
            'onnx': (nh_onnx, f"{base_url}/models/ngoc_huyen/ngochuyennew.onnx"),
            'json': (nh_json, f"{base_url}/models/ngoc_huyen/ngochuyennew.onnx.json")
        },
        'th_TH-mms_female-medium': {
            'onnx': (models_dir / 'th_TH-mms_female-medium.onnx', f"{base_url}/models/th_TH-mms_female-medium.onnx"),
            'json': (models_dir / 'th_TH-mms_female-medium.onnx.json', f"{base_url}/models/th_TH-mms_female-medium.onnx.json")
        },
        'khmer_tts_v3': {
            'onnx': (models_dir / 'khmer_tts_v3.onnx', f"{base_url}/models/khmer_tts_v3.onnx"),
            'json': (models_dir / 'khmer_tts_v3.json', f"{base_url}/models/khmer_tts_v3.json")
        }
    }

    for name, files in specs.items():
        for kind, (path, url) in files.items():
            if not path.is_file() or path.stat().st_size == 0:
                LOG.info("Fetching [%s] %s -> %s", name, url, path.name)
                try:
                    req = urllib.request.Request(
                        url,
                        headers={"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36"}
                    )
                    with urllib.request.urlopen(req, timeout=120) as resp, open(path, "wb") as out_f:
                        while True:
                            chunk = resp.read(1024 * 1024)
                            if not chunk:
                                break
                            out_f.write(chunk)
                    LOG.info("Saved %s (%d bytes)", path.name, path.stat().st_size)
                except Exception as exc:
                    LOG.error("Failed to download %s: %s", url, exc)
                    raise


def load_all_voices(models_dir: Path, use_cuda: bool = True):
    models_dir = Path(models_dir)
    voices = {}

    # 1. ngochuyennew
    nh_onnx = models_dir / 'ngochuyennew.onnx'
    if not nh_onnx.is_file():
        nh_onnx = models_dir / 'ngoc_huyen' / 'ngochuyennew.onnx'
    voices['ngochuyennew'] = PiperVoice(nh_onnx, use_cuda=use_cuda)

    # 2. th_TH-mms_female-medium
    th_onnx = models_dir / 'th_TH-mms_female-medium.onnx'
    voices['th_TH-mms_female-medium'] = PiperVoice(th_onnx, use_cuda=use_cuda)

    # 3. khmer_tts_v3
    km_onnx = models_dir / 'khmer_tts_v3.onnx'
    km_json = models_dir / 'khmer_tts_v3.json'
    providers = ['CUDAExecutionProvider', 'CPUExecutionProvider'] if use_cuda else ['CPUExecutionProvider']
    voices['khmer_tts_v3'] = KhmerVoice.load(km_onnx, km_json, sample_rate=22050, providers=providers)

    return voices


def run_ws_loop(server_url: str, token: str, worker_id: str, worker: ColabTTSWorker, stop: threading.Event, concurrency: int = 20):
    import websocket

    parsed = urlsplit(server_url)
    if parsed.scheme not in ('ws', 'wss') or not parsed.netloc:
        raise ValueError(f"Invalid server URL: {server_url}")

    query = dict(parse_qsl(parsed.query))
    if token:
        query['token'] = token
    url = urlunsplit((parsed.scheme, parsed.netloc, parsed.path, urlencode(query), ''))

    models = sorted('piper:' + name for name in worker.voices)
    reg = {
        'worker_id': worker_id,
        'model': models[0],
        'models': models,
        'capabilities': ['audio_speech', 'tts'],
        'max_concurrency': concurrency,
        'token': token or '',
    }

    LOG.info("[REGISTRATION] Preparing inbound registration: worker_id=%s, concurrency=%d, models=%s",
             worker_id, concurrency, models)

    while not stop.is_set():
        sock = None
        try:
            headers = {'X-Worker-Token': token} if token else {}
            sock = websocket.create_connection(url, timeout=15, header=headers, enable_multithread=True)
            write_lock = threading.Lock()

            def send(message):
                with write_lock:
                    try:
                        sock.send(json.dumps(message, ensure_ascii=False))
                    except Exception as e:
                        LOG.warning("Failed to send message: %s", e)

            # Send registration
            send(reg)
            ack_raw = sock.recv()
            ack = json.loads(ack_raw) if ack_raw else {}
            if ack.get('type') != 'registered':
                raise RuntimeError(f"Registration rejected: {ack}")

            LOG.info("[COLAB_WORKER_ONLINE] Registered with WorkerHub! Worker ID: %s, Max Concurrency: %d",
                     worker_id, concurrency)

            sock.settimeout(2.0)
            while not stop.is_set():
                try:
                    data = sock.recv()
                except websocket.WebSocketTimeoutException:
                    continue
                except Exception as e:
                    if not stop.is_set():
                        LOG.warning("Socket read error: %s", e)
                    break

                if not data:
                    break
                try:
                    msg = json.loads(data)
                except Exception:
                    continue
                if isinstance(msg, dict):
                    worker.dispatch(msg, send)

        except Exception as exc:
            if not stop.is_set():
                LOG.warning("Worker disconnected (%s); reconnecting in 3s...", exc)
                stop.wait(3.0)
        finally:
            if sock:
                try:
                    sock.close()
                except Exception:
                    pass


def main():
    parser = argparse.ArgumentParser(description="Colab TTS GPU Worker")
    parser.add_argument('--server', default='wss://hub.maika.sbs/api/llm/ws/worker', help='WorkerHub WebSocket endpoint')
    parser.add_argument('--token', default=os.environ.get('WORKER_AUTH_TOKEN', 'omni-secret-key-123'), help='Worker auth token')
    parser.add_argument('--worker-id', default='colab-t4-tts-worker', help='Worker registration ID')
    parser.add_argument('--models-dir', default='models', help='Directory for cached ONNX models')
    parser.add_argument('--download-url', default='https://hub.maika.sbs', help='Base HTTP URL to download models from')
    parser.add_argument('--concurrency', type=int, default=20, help='Max concurrency capacity (default: 20)')
    parser.add_argument('--threads-per-voice', type=int, default=4, help='Synthesis threads per voice lane')
    parser.add_argument('--no-cuda', action='store_true', help='Force CPU execution')

    args = parser.parse_args()

    models_dir = Path(args.models_dir)
    ensure_models(models_dir, args.download_url)

    use_cuda = not args.no_cuda
    LOG.info("Loading voices from %s (CUDA=%s)...", models_dir, use_cuda)
    voices = load_all_voices(models_dir, use_cuda=use_cuda)
    LOG.info("Voices loaded successfully: %s", list(voices.keys()))

    worker = ColabTTSWorker(voices, queue_size=32, threads_per_voice=args.threads_per_voice)
    stop = threading.Event()

    def handle_signal(sig, frame):
        LOG.info("Shutting down worker...")
        stop.set()
        worker.close()

    signal.signal(signal.SIGINT, handle_signal)
    signal.signal(signal.SIGTERM, handle_signal)

    try:
        run_ws_loop(args.server, args.token, args.worker_id, worker, stop, concurrency=args.concurrency)
    finally:
        worker.close()


if __name__ == '__main__':
    main()
