"""Colab TTS GPU Worker for Sever_provider.

Self-contained worker designed to run in Google Colab (or remote GPU instance)
under NVIDIA T4 CUDA acceleration.
- Self-downloads 3 ONNX voices:
    * ngochuyennew (Vietnamese)
    * th_TH-mms_female-medium (Thai)
    * khmer_tts_v3 (Khmer)
- Preloads models into memory using CUDAExecutionProvider.
- Connects inbound to Master Server via WebSocket:
    wss://hub.maika.sbs/api/llm/ws/worker (or ws://192.168.1.117:18080/api/llm/ws/worker).
- Registers worker_id with max_concurrency: 20.
"""
